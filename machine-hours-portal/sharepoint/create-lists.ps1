function Ensure-List([string]$Name, [string]$Description) {
  $l = Get-PnPList -Identity $Name -ErrorAction SilentlyContinue
  if (-not $l) { Write-Host "Creating list $Name"; $l = New-PnPList -Title $Name -Template GenericList -EnableVersioning -OnQuickLaunch:$false; Set-PnPList -Identity $Name -Description $Description | Out-Null }
  else { Write-Host "List $Name exists" }
}
function Ensure-Field([string]$List, [string]$Name, [string]$Type, [bool]$Indexed) {
  $f = Get-PnPField -List $List -Identity $Name -ErrorAction SilentlyContinue
  if (-not $f) {
    Write-Host "  + $Name ($Type)"
    $f = Add-PnPField -List $List -DisplayName $Name -InternalName $Name -Type $Type -AddToDefaultView
    if ($Type -eq "Note") { Set-PnPField -List $List -Identity $Name -Values @{ RichText = $false; NumberOfLines = 6 } | Out-Null }
  }
  if ($Indexed) { Set-PnPField -List $List -Identity $Name -Values @{ Indexed = $true } | Out-Null }
}

