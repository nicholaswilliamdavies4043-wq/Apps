#!/usr/bin/env node
/*
 * SharePoint setup helper for the Machine Hours Portal.
 *
 *   node scripts/sharepoint-setup.js --check     test sign-in, find the site, report missing lists/columns
 *   node scripts/sharepoint-setup.js --create    create missing lists and columns (app needs "manage" on the site)
 *   node scripts/sharepoint-setup.js --migrate   upload data/db.json into EMPTY lists
 *   node scripts/sharepoint-setup.js --ps1       (re)write sharepoint/create-lists.ps1 (PnP PowerShell alternative)
 *   node scripts/sharepoint-setup.js --docs      (re)write sharepoint/LISTS.md (column reference)
 *
 * Reads the same .env as the server (SP_TENANT_ID, SP_CLIENT_ID, SP_CLIENT_SECRET, SP_SITE_URL, SP_LIST_PREFIX).
 */
'use strict';
const fs = require('fs');
const path = require('path');
const ROOT = path.join(__dirname, '..');
loadEnvFile(path.join(ROOT, '.env'));
const Core = require('../public/js/core.js');
const { SharePointStore, LISTS, allColumns } = require('../storage/sharepoint.js');
const { listName } = require('../storage/sp-schema.js');

const args = process.argv.slice(2);
const prefix = process.env.SP_LIST_PREFIX != null ? process.env.SP_LIST_PREFIX : 'MHP_';
const DATA_DIR = path.resolve(process.env.DATA_DIR || path.join(ROOT, 'data'));

function store() {
  const need = ['SP_TENANT_ID', 'SP_CLIENT_ID', 'SP_CLIENT_SECRET'].filter((k) => !process.env[k]);
  if (!process.env.SP_SITE_URL && !process.env.SP_SITE_ID) need.push('SP_SITE_URL');
  if (need.length) { console.error('Missing settings in .env: ' + need.join(', ')); process.exit(1); }
  fs.mkdirSync(DATA_DIR, { recursive: true });
  return new SharePointStore({
    tenantId: process.env.SP_TENANT_ID, clientId: process.env.SP_CLIENT_ID, clientSecret: process.env.SP_CLIENT_SECRET,
    siteUrl: process.env.SP_SITE_URL, siteId: process.env.SP_SITE_ID, prefix, stateFile: path.join(DATA_DIR, 'sharepoint-state.json'),
    owners: (process.env.SUPERUSER_EMAILS || Core.DEFAULT_OWNERS.join(',')).split(',').map((e) => e.trim().toLowerCase()),
    graphBase: process.env.SP_GRAPH_BASE || undefined, loginBase: process.env.SP_LOGIN_BASE || undefined
  });
}

const PNP_TYPE = { text: 'Text', note: 'Note', number: 'Number', boolean: 'Boolean', dateTime: 'DateTime' };
function ps1() {
  const L = [];
  L.push('<#');
  L.push('  Machine Hours Portal - create the SharePoint lists (PnP PowerShell).');
  L.push('  Run as a SharePoint site owner. Requires: Install-Module PnP.PowerShell (PowerShell 7.2+)');
  L.push('  and an Entra ID app registration for PnP interactive sign-in (-ClientId), see README.');
  L.push('');
  L.push('  .\\create-lists.ps1 -SiteUrl https://<tenant>.sharepoint.com/sites/<site> -PnPClientId <guid>');
  L.push('  Optional: -Prefix MHP_   -GrantAppId <portal app client id>  (grants the portal app Write on this site;');
  L.push('            granting needs a SharePoint/Global admin)');
  L.push('  Generated by scripts/sharepoint-setup.js --ps1. Safe to run more than once.');
  L.push('#>');
  L.push('param(');
  L.push('  [Parameter(Mandatory=$true)][string]$SiteUrl,');
  L.push('  [Parameter(Mandatory=$true)][string]$PnPClientId,');
  L.push('  [string]$Prefix = "' + prefix + '",');
  L.push('  [string]$GrantAppId = ""');
  L.push(')');
  L.push('$ErrorActionPreference = "Stop"');
  L.push('Connect-PnPOnline -Url $SiteUrl -Interactive -ClientId $PnPClientId');
  L.push('');
  L.push('function Ensure-List([string]$Name, [string]$Description) {');
  L.push('  $l = Get-PnPList -Identity $Name -ErrorAction SilentlyContinue');
  L.push('  if (-not $l) { Write-Host "Creating list $Name"; $l = New-PnPList -Title $Name -Template GenericList -EnableVersioning -OnQuickLaunch:$false; Set-PnPList -Identity $Name -Description $Description | Out-Null }');
  L.push('  else { Write-Host "List $Name exists" }');
  L.push('}');
  L.push('function Ensure-Field([string]$List, [string]$Name, [string]$Type, [bool]$Indexed) {');
  L.push('  $f = Get-PnPField -List $List -Identity $Name -ErrorAction SilentlyContinue');
  L.push('  if (-not $f) {');
  L.push('    Write-Host "  + $Name ($Type)"');
  L.push('    $f = Add-PnPField -List $List -DisplayName $Name -InternalName $Name -Type $Type -AddToDefaultView');
  L.push('    if ($Type -eq "Note") { Set-PnPField -List $List -Identity $Name -Values @{ RichText = $false; NumberOfLines = 6 } | Out-Null }');
  L.push('  }');
  L.push('  if ($Indexed) { Set-PnPField -List $List -Identity $Name -Values @{ Indexed = $true } | Out-Null }');
  L.push('}');
  L.push('');
  for (const l of LISTS) {
    L.push('# ---- ' + l.name + ' — ' + l.desc);
    L.push('$n = $Prefix + "' + l.name + '"');
    L.push('Ensure-List $n "Machine Hours Portal - ' + l.desc.replace(/"/g, "'") + '"');
    for (const [name, type, , o] of allColumns(l)) L.push('Ensure-Field $n "' + name + '" "' + PNP_TYPE[type] + '" $' + (o && o.indexed ? 'true' : 'false'));
    L.push('');
  }
  L.push('if ($GrantAppId) {');
  L.push('  Write-Host "Granting Write on this site to app $GrantAppId (Sites.Selected)"');
  L.push('  Grant-PnPAzureADAppSitePermission -AppId $GrantAppId -DisplayName "Machine Hours Portal" -Permissions Write -Site $SiteUrl');
  L.push('}');
  L.push('Write-Host "Done."');
  return L.join('\r\n').replace(/[^\x00-\x7F]/g, '-') + '\r\n';
}

function docs() {
  const L = ['# SharePoint lists used by the Machine Hours Portal', '',
    'List names start with the prefix `' + prefix + '` (setting `SP_LIST_PREFIX`). Every list also has **Title**, **AppId** (indexed) and **AppJson**.',
    '', '- **AppJson** holds the full record and is the source of truth for anything without its own column. Do not edit it by hand.',
    '- Columns marked ✎ can be edited directly in SharePoint, and the app picks up the change on its next refresh (every `SP_PULL_MINUTES`, default 5). Clearing a value in SharePoint is not copied back; change it in the app instead.',
    '- Columns marked ƒ are calculated by the app (e.g. start readings, hours, check) and are overwritten.',
    '- Cover photos are stored as files in the site\'s default document library under `MachineHoursPortal/covers/`.',
    '- Sessions, superuser passwords and roles, notifications and app settings stay on the portal server and are **not** stored in SharePoint.', ''];
  for (const l of LISTS) {
    L.push('## ' + listName(prefix, l), '', l.desc, '', '| Column | Type | Indexed | |', '|---|---|---|---|');
    L.push('| Title | text |  | ' + (l.editTitle ? '✎ ' + l.editTitle : 'ƒ label') + ' |');
    for (const [name, type, src, o] of l.cols) L.push('| ' + name + ' | ' + type + ' | ' + (o && o.indexed ? 'yes' : '') + ' | ' + (typeof src === 'function' ? 'ƒ' : '') + (o && o.edit ? '✎' : '') + ' |');
    L.push('');
  }
  return L.join('\n');
}

(async () => {
  try {
    if (args.includes('--ps1')) {
      const f = path.join(ROOT, 'sharepoint', 'create-lists.ps1');
      fs.mkdirSync(path.dirname(f), { recursive: true }); fs.writeFileSync(f, ps1()); console.log('Wrote ' + f);
    }
    if (args.includes('--docs')) {
      const f = path.join(ROOT, 'sharepoint', 'LISTS.md');
      fs.mkdirSync(path.dirname(f), { recursive: true }); fs.writeFileSync(f, docs()); console.log('Wrote ' + f);
    }
    if (args.includes('--check') || args.includes('--create')) {
      const s = store();
      const sid = await s.resolveSite();
      console.log('✓ Signed in and found the site: ' + sid);
      const rep = await s.ensureLists(args.includes('--create'));
      for (const r of rep) console.log((/MISSING/.test(r.action) ? '✗ ' : '✓ ') + r.list.padEnd(28) + r.action);
    }
    if (args.includes('--migrate')) {
      const s = store();
      const db = Core.migrate(JSON.parse(fs.readFileSync(path.join(DATA_DIR, 'db.json'), 'utf8')));
      await s.ensureLists(false);
      const data = await s.readAll();
      const count = LISTS.reduce((a, l) => a + data[l.key].length, 0);
      if (count && !args.includes('--force')) { console.error('The lists already contain ' + count + ' items. Migration only fills empty lists (use --force to add anyway).'); process.exit(1); }
      for (const l of LISTS) { s.state.map[l.key] = {}; s.state.snap[l.key] = {}; }
      const r = await s._flush(db);
      console.log('Uploaded ' + r.sent + ' records' + (r.failed ? ' (' + r.failed + ' failed, run again)' : ''));
    }
    if (!args.length) console.log(fs.readFileSync(__filename, 'utf8').split('*/')[0]);
  } catch (e) { console.error('✗ ' + e.message); process.exit(1); }
})();

function loadEnvFile(f) {
  if (!fs.existsSync(f)) return;
  for (const line of fs.readFileSync(f, 'utf8').split(/\r?\n/)) {
    const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*)\s*$/);
    if (m && !(m[1] in process.env)) process.env[m[1]] = m[2].replace(/^["']|["']$/g, '');
  }
}
